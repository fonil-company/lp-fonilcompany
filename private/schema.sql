CREATE TABLE IF NOT EXISTS leads (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  criado_em          DATETIME NOT NULL COMMENT 'America/Sao_Paulo',
  event_id           CHAR(36) NOT NULL,
  nome               VARCHAR(120) NOT NULL,
  email              VARCHAR(160) NOT NULL,
  empresa            VARCHAR(160) NOT NULL,
  whatsapp           VARCHAR(11)  NOT NULL,
  faturamento        VARCHAR(40)  NOT NULL,
  cargo              VARCHAR(40)  NOT NULL,
  utm_source         VARCHAR(255) NULL,
  utm_medium         VARCHAR(255) NULL,
  utm_campaign       VARCHAR(255) NULL,
  utm_term           VARCHAR(255) NULL,
  utm_content        VARCHAR(255) NULL,
  gclid              VARCHAR(255) NULL,
  fbclid             VARCHAR(255) NULL,
  pagina             VARCHAR(500) NULL,
  ip_hash            CHAR(64)     NOT NULL,
  user_agent         VARCHAR(255) NULL,
  status_crm         ENUM('enviado','pendente') NOT NULL DEFAULT 'pendente',
  crm_tentativas     SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  status_diagnostico ENUM('novo','em contato','agendado','realizado','sem aderência') NOT NULL DEFAULT 'novo',
  UNIQUE KEY uq_event (event_id),
  KEY idx_ip_time (ip_hash, criado_em),
  KEY idx_crm (status_crm)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
